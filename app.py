"""
CodeCraftHub - Simple Flask REST API

This application provides CRUD operations for courses and stores the
course data in a local JSON file named courses.json.

Run the application with:

    python app.py
"""

import json
import re
from datetime import datetime, timezone
from pathlib import Path

from flask import Flask, jsonify, request


# Create the Flask application
app = Flask(__name__)


# Store courses.json in the same directory as this app.py file.
# This avoids problems caused by running the application from another directory.
DATA_FILE = Path(__file__).resolve().parent / "courses.json"


# The only valid course status values
ALLOWED_STATUSES = {
    "Not Started",
    "In Progress",
    "Completed",
}


class StorageError(Exception):
    """Used when the courses.json file cannot be read or written."""


def ensure_data_file():
    """
    Create courses.json automatically if it does not already exist.

    The file starts with an empty JSON list because courses will be stored
    as a list of objects.
    """
    if not DATA_FILE.exists():
        try:
            DATA_FILE.write_text("[]", encoding="utf-8")
        except OSError as error:
            raise StorageError(
                f"Unable to create data file: {error}"
            ) from error


def load_courses():
    """
    Read and return all courses from courses.json.

    Returns:
        list: A list of course dictionaries.

    Raises:
        StorageError: If the file cannot be created, read, or parsed.
    """
    ensure_data_file()

    try:
        with DATA_FILE.open("r", encoding="utf-8") as file:
            courses = json.load(file)
    except OSError as error:
        raise StorageError(
            f"Unable to read data file: {error}"
        ) from error
    except json.JSONDecodeError as error:
        raise StorageError(
            f"Data file contains invalid JSON: {error}"
        ) from error

    # The JSON file should contain a list of courses.
    if not isinstance(courses, list):
        raise StorageError("Data file must contain a JSON list.")

    return courses


def save_courses(courses):
    """
    Save all courses to courses.json.

    Args:
        courses (list): The list of course dictionaries.

    Raises:
        StorageError: If the file cannot be written.
    """
    try:
        with DATA_FILE.open("w", encoding="utf-8") as file:
            json.dump(courses, file, indent=2)
    except OSError as error:
        raise StorageError(
            f"Unable to write data file: {error}"
        ) from error


def get_next_course_id(courses):
    """
    Generate the next course ID.

    The first course receives ID 1. After that, the next ID is one
    greater than the current highest ID.
    """
    if not courses:
        return 1

    return max(course.get("id", 0) for course in courses) + 1


def create_timestamp():
    """
    Create a UTC timestamp for the created_at field.

    Example:
        2026-11-01T14:30:00.123456Z
    """
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def validate_course_data(data):
    """
    Validate the fields supplied in a request body.

    All course fields are required when creating or updating a course.
    The id and created_at fields are generated by the server and should
    not be supplied by the client.

    Args:
        data (dict): JSON data received from the client.

    Returns:
        str or None: An error message, or None if the data is valid.
    """
    if not isinstance(data, dict):
        return "Request body must be a JSON object."

    required_fields = [
        "name",
        "description",
        "target_date",
        "status",
    ]

    # Check that every required field exists and is not empty.
    for field in required_fields:
        if field not in data:
            return f"Missing required field: {field}"

        if not isinstance(data[field], str) or not data[field].strip():
            return f"Field '{field}' must be a non-empty string."

    # Check that the status is one of the allowed values.
    if data["status"] not in ALLOWED_STATUSES:
        return (
            "Invalid status. Status must be one of: "
            "Not Started, In Progress, Completed."
        )

    # Check the exact YYYY-MM-DD format.
    target_date = data["target_date"]

    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", target_date):
        return "target_date must use YYYY-MM-DD format."

    # Check that the date is a real calendar date.
    try:
        datetime.strptime(target_date, "%Y-%m-%d")
    except ValueError:
        return "target_date must be a valid date in YYYY-MM-DD format."

    return None


def find_course(courses, course_id):
    """
    Find a course by its ID.

    Args:
        courses (list): All courses.
        course_id (int): The ID to search for.

    Returns:
        dict or None: The matching course, or None if not found.
    """
    for course in courses:
        if course.get("id") == course_id:
            return course

    return None


@app.route("/api/courses", methods=["POST"])
def create_course():
    """
    Add a new course.

    Expected JSON body:

    {
        "name": "Python Basics",
        "description": "Learn Python fundamentals.",
        "target_date": "2026-12-31",
        "status": "Not Started"
    }
    """
    # silent=True prevents Flask from raising an HTML error page
    # when the request body is missing or contains invalid JSON.
    data = request.get_json(silent=True)

    if data is None:
        return jsonify({
            "error": "Request body must contain valid JSON."
        }), 400

    validation_error = validate_course_data(data)

    if validation_error:
        return jsonify({"error": validation_error}), 400

    try:
        courses = load_courses()

        new_course = {
            "id": get_next_course_id(courses),
            "name": data["name"].strip(),
            "description": data["description"].strip(),
            "target_date": data["target_date"],
            "status": data["status"],
            "created_at": create_timestamp(),
        }

        courses.append(new_course)
        save_courses(courses)

    except StorageError as error:
        return jsonify({
            "error": "A storage error occurred.",
            "details": str(error),
        }), 500

    return jsonify(new_course), 201


@app.route("/api/courses", methods=["GET"])
def get_courses():
    """Return all courses."""
    try:
        courses = load_courses()
    except StorageError as error:
        return jsonify({
            "error": "A storage error occurred.",
            "details": str(error),
        }), 500

    return jsonify(courses), 200


@app.route("/api/courses/<int:course_id>", methods=["GET"])
def get_course(course_id):
    """Return one course by ID."""
    try:
        courses = load_courses()
    except StorageError as error:
        return jsonify({
            "error": "A storage error occurred.",
            "details": str(error),
        }), 500

    course = find_course(courses, course_id)

    if course is None:
        return jsonify({
            "error": f"Course with ID {course_id} was not found."
        }), 404

    return jsonify(course), 200


@app.route("/api/courses/<int:course_id>", methods=["PUT"])
def update_course(course_id):
    """
    Update an existing course.

    The request must include all editable course fields:

    {
        "name": "Updated Course Name",
        "description": "Updated description.",
        "target_date": "2026-12-31",
        "status": "In Progress"
    }

    The existing id and created_at values are preserved.
    """
    data = request.get_json(silent=True)

    if data is None:
        return jsonify({
            "error": "Request body must contain valid JSON."
        }), 400

    validation_error = validate_course_data(data)

    if validation_error:
        return jsonify({"error": validation_error}), 400

    try:
        courses = load_courses()
    except StorageError as error:
        return jsonify({
            "error": "A storage error occurred.",
            "details": str(error),
        }), 500

    course = find_course(courses, course_id)

    if course is None:
        return jsonify({
            "error": f"Course with ID {course_id} was not found."
        }), 404

    # Update only the fields that clients are allowed to change.
    course["name"] = data["name"].strip()
    course["description"] = data["description"].strip()
    course["target_date"] = data["target_date"]
    course["status"] = data["status"]

    try:
        save_courses(courses)
    except StorageError as error:
        return jsonify({
            "error": "A storage error occurred.",
            "details": str(error),
        }), 500

    return jsonify(course), 200


@app.route("/api/courses/<int:course_id>", methods=["DELETE"])
def delete_course(course_id):
    """Delete a course by ID."""
    try:
        courses = load_courses()
    except StorageError as error:
        return jsonify({
            "error": "A storage error occurred.",
            "details": str(error),
        }), 500

    course = find_course(courses, course_id)

    if course is None:
        return jsonify({
            "error": f"Course with ID {course_id} was not found."
        }), 404

    # Remove the matching course from the list.
    courses.remove(course)

    try:
        save_courses(courses)
    except StorageError as error:
        return jsonify({
            "error": "A storage error occurred.",
            "details": str(error),
        }), 500

    return jsonify({
        "message": "Course deleted successfully.",
        "course": course,
    }), 200


@app.errorhandler(404)
def handle_not_found(error):
    """
    Return JSON instead of Flask's default HTML 404 page.

    This is useful when a client requests an endpoint that does not exist.
    """
    return jsonify({
        "error": "The requested endpoint was not found."
    }), 404


@app.errorhandler(405)
def handle_method_not_allowed(error):
    """Return JSON when the HTTP method is not supported."""
    return jsonify({
        "error": "The HTTP method is not allowed for this endpoint."
    }), 405


if __name__ == "__main__":
    # Create courses.json when the application starts.
    # Any storage error is reported, but Flask can still start so that
    # API requests can return a JSON error response.
    try:
        ensure_data_file()
        print(f"Using data file: {DATA_FILE}")
    except StorageError as error:
        print(f"Warning: {error}")

    # debug=True is useful while learning and developing.
    # Turn it off in production.
    app.run(debug=True)